export const PRIVACY_NOTICE = `JOBLINKED — PESO SANTA MARIA
Privacy Notice (Data Privacy Act of 2012, RA 10173)

JobLinked is the employment matching service operated with the Public Employment
Service Office (PESO) of Santa Maria, Bulacan. This notice explains what personal
information we collect, why we collect it, how it is protected, and the rights
you can exercise over it.

1. Information we collect
- Account and identity details: name, residential address or barangay, email
  address, mobile number, and account credentials.
- Employment profile: education, skills, qualifications, certifications, work
  experience, employment status, and job preferences.
- Application records: résumés and supporting documents you upload, the
  vacancies you applied to, referral records, and recruitment status updates.
- Service records: notifications sent to you, and technical logs needed to keep
  the service secure (access times, request identifiers).

Only information necessary for the requested service is collected. Required and
optional fields are identified in the forms. Sensitive information is requested
only when necessary, with its purpose and legal basis explained before collection.

2. Why we use it
- Create and manage your JobLinked account and applicant profile.
- Match your qualifications and preferences with job vacancies.
- Process applications and facilitate PESO employment assistance and referrals.
- Display and update your application status.
- Send account, application, and service notifications.
- Prepare authorized municipal employment reports using aggregated or anonymized
  information.

3. Who may access it
Authorized PESO personnel may access the information needed to deliver employment
services and prepare authorized reports. Technical personnel and service providers
may process information only as necessary to operate and secure JobLinked, subject
to confidentiality and security obligations.

When you apply for a vacancy, the application screen names the receiving employer
and the information and documents to be shared before you confirm submission.
Sharing your profile with other prospective employers for additional PESO referrals
requires a separate legal basis, including your optional consent where applicable.
Your profile is not sold and is not published as a public applicant directory.

4. How it is stored and protected
Appropriate organizational, physical, and technical safeguards apply, including
access restrictions to authorized users, encrypted transport, and audit logging of
administrative actions. Records are retained only while necessary for the stated
services or as required by applicable law and government records rules. When
retention is no longer necessary, information is securely deleted, disposed of, or
anonymized. Closing your account does not automatically erase records that must
lawfully be retained.

5. Your rights
Subject to applicable law, you may request access to your records, ask for
corrections, object to processing, withdraw consent, or request deletion or
blocking of your information. You may file a complaint with the National Privacy
Commission. Requests are submitted to the PESO office handling your registration
for referral to the Municipality's designated Data Protection Officer.

Withdrawal applies to future processing based on consent. It does not invalidate
earlier lawful processing or override legal retention requirements.

6. Legal basis
Information is processed in accordance with RA 10173, its implementing rules,
applicable PESO legislation, and relevant municipal requirements. Processing
required for government functions or legal obligations is identified accordingly;
where consent is the applicable basis, it is requested specifically.

7. Questions and changes
Material changes to this notice are communicated through JobLinked, and any new
purpose requiring consent is presented separately before it applies. Questions
about this notice may be raised with the PESO office handling your registration.`

